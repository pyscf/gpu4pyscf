lib.logger.note(mol, 'Total wall time: %.2f s (%02d:%02d:%05.2f)',
                elapsed, int(hours), int(minutes), seconds)
mol.stdout.flush()
print(f'Calculation finished. Total wall time: {elapsed:.2f} s; see testout.out')

